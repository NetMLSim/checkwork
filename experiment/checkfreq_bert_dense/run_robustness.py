# Grounded in real hardware ceilings.
STORAGE_TIERS = {
    "nvme_fast": (25.0, 7.0),   # PCIe Gen5 x16 GPU->host, NVMe Gen4 SSD persist
    "nvme_std":  (12.0, 3.0),   # PCIe Gen4 x16 GPU->host, NVMe SATA SSD persist
    "sata_slow": (6.0,  0.5),   # constrained host-staging, SATA SSD persist
}

