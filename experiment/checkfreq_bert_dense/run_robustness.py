RESULTS_DIR = SWEEP_DIR / "results"
LOG_DIR = RESULTS_DIR / "timeline_logs"
CONFIG_DIR = SWEEP_DIR / "config"
CHAKRA_PY = ROOT / "chakra_env" / "bin" / "python3"
if not CHAKRA_PY.exists():
    CHAKRA_PY = Path(sys.executable)

NUM_ITERATIONS = 200
DP_SIZE = 8
PP_SIZE = 1
TP_SIZE = 1

# Cycles per micro-second. ASTRA-sim cycle = duration_micros * FREQ_GHZ * 1000.
FREQ_GHZ = 1.5
CYCLES_PER_MICROS = int(FREQ_GHZ * 1000)  # 1500

