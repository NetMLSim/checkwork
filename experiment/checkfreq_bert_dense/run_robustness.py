#!/usr/bin/env python3
"""
CheckFreq dense BERT sweep.

A higher-resolution sibling of ``experiment/checkfreq_robustness/`` that
focuses on a **single model (BERT)** and walks the (frequency, checkpoint
size) plane in fine steps so the heatmap and overhead-vs-size plots can show
the smooth shape of the overhead surface.

  Axis 1  --  Model architecture
              ``bert`` only (24L/1024d/512S/64B).
  Axis 2  --  Checkpoint frequency
              ``checkpoint_every_n in {10, 20, 30, ..., 100}``  (10 values).
  Axis 3  --  Checkpoint size per rank
              ``{500, 1000, 1500, ..., 5000}`` MB  (10 values).

Storage tier and network topology are *fixed* at the defaults
(``nvme_std`` = 12 / 3 GB/s and ``network_8_balanced``) so the 10x10 grid is
a clean OFAT slice over (freq, size) -- exactly the surface the reviewers
asked for.

Total: 1 baseline + 2 modes x 10 freqs x 10 sizes = **201 ASTRA-sim runs**.

Outputs:
  results/runs.csv      -- one row per ASTRA-sim run.
  results/runs.json     -- same, with full config metadata.
  results/summary.csv   -- per-cell (cf, sync) overhead pivot.
  results/plots/*       -- generated by plot_results.py.

Usage:
  python3 run_robustness.py                 # full study (~30-40 min)
  python3 run_robustness.py --quick         # minimal subset for smoke test
  python3 run_robustness.py --skip-gen      # reuse cached traces
  python3 run_robustness.py --skip-sim      # only generate traces
  python3 run_robustness.py --local         # local topo sim (no Docker)
"""
