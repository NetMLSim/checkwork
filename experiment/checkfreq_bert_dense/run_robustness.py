BASE_YAML = """model:
  name: "{name}"
  num_layers: {num_layers}
  sequence_len: {sequence_len}
  vocab_size: {vocab_size}
  hidden_size: {hidden_size}
  batch_size: {batch_size}
  num_microbatches: {num_microbatches}
  bytes_per_val: {bytes_per_val}
  scale: {scale}

parallelism:
  dp_size: {dp}
  pp_size: {pp}
  tp_size: {tp}

num_iterations: {num_iterations}
"""

CKPT_YAML_TMPL = """model:
  name: "{name}"
  num_layers: {num_layers}
  sequence_len: {sequence_len}
  vocab_size: {vocab_size}
  hidden_size: {hidden_size}
  batch_size: {batch_size}
  num_microbatches: {num_microbatches}
  bytes_per_val: {bytes_per_val}
  scale: {scale}

parallelism:
  dp_size: {dp}
  pp_size: {pp}
  tp_size: {tp}

num_iterations: {num_iterations}

wrapper:
  type: "checkpoint"
  mode: "{wrapper_mode}"
  checkpoint_every_n: {checkpoint_every_n}
  state_multiplier: {state_multiplier}
{extra}
  snapshot_overhead_multiplier: 1.0
  persist_overhead_multiplier: 5.0
  snapshot_duration_micros: {snapshot_micros}
  persist_duration_micros: {persist_micros}
"""


def _yaml_for_cell(cell: Cell) -> str:
    model = MODELS[cell.model]
    common = dict(
        name=model["name"],
        num_layers=model["num_layers"],
        sequence_len=model["sequence_len"],
        vocab_size=model["vocab_size"],
        hidden_size=model["hidden_size"],
        batch_size=model["batch_size"],
        num_microbatches=model["num_microbatches"],
        bytes_per_val=model["bytes_per_val"],
        scale=model["scale"],
        dp=DP_SIZE,
        pp=PP_SIZE,
        tp=TP_SIZE,
        num_iterations=cell.num_iterations,
    )
    if cell.mode == "baseline":
        return BASE_YAML.format(**common)

    sm = state_multiplier_for_target_mb(cell.size_mb, model)
    bytes_per_rank = cell.size_mb * 1024 * 1024
    snap_us, pers_us = storage_durations_micros(bytes_per_rank, cell.storage)
    extra = ""
    if cell.mode == "checkfreq_like":
        wrapper_mode = "checkfreq_like"
        extra = "  kickoff_cost_micros: 0\n  drain_when_backpressure: false\n  persist_in_background_no_graph: true"
    elif cell.mode == "sync":
        wrapper_mode = "sync"
    else:
        raise ValueError(f"Unsupported cell mode: {cell.mode}")
    return CKPT_YAML_TMPL.format(
        **common,
        wrapper_mode=wrapper_mode,
        checkpoint_every_n=cell.freq,
        state_multiplier=sm,
        extra=extra,
        snapshot_micros=snap_us,
        persist_micros=pers_us,
    )


def _trace_complete(trace_dir: Path, model: dict, num_iterations: int) -> bool:
    et_dir = trace_dir / "et"
    if not et_dir.exists() or not (trace_dir / "comm_groups.json").exists():
        return False
    out_name = workload_name(model, num_iterations)
    n_npus = DP_SIZE * PP_SIZE * TP_SIZE
    return all((et_dir / f"{out_name}.{i}.et").exists() for i in range(n_npus))


def generate_trace(cell: Cell, verbose: bool = False) -> Path:
    """Generate ET traces for one cell into traces/<trace_key>/. Caches by key."""
    model = MODELS[cell.model]
    trace_dir = TR / cell.trace_key()
    trace_dir.mkdir(parents=True, exist_ok=True)
    (trace_dir / "et").mkdir(exist_ok=True)
    if _trace_complete(trace_dir, model, cell.num_iterations):
        if verbose:
            print(f"  [cache] {trace_dir.name}")
        return trace_dir

    yaml_text = _yaml_for_cell(cell)
    yaml_path = ML / f"_dense_{cell.trace_key()}.yaml"
    yaml_path.write_text(yaml_text)
    try:
        r = subprocess.run(
            [str(CHAKRA_PY), "synthesise_workload.py", "-c", str(yaml_path)],
            cwd=ML,
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            raise RuntimeError(f"CheckWork trace generation failed for {cell}:\nstdout={r.stdout}\nstderr={r.stderr}")
    finally:
        yaml_path.unlink(missing_ok=True)

    out_name = workload_name(model, cell.num_iterations)
    out = ML / "output" / out_name
    (trace_dir / "comm_groups.json").write_bytes((out / "comm_groups.json").read_bytes())
    for et in (out / "et").glob("*.et"):
        (trace_dir / "et" / et.name).write_bytes(et.read_bytes())
    return trace_dir


# ----------------------------------------------------------------------------
# Simulation
# ----------------------------------------------------------------------------
def run_astrasim(trace_dir: Path, network_yml: Path, workload_basename: str, log_path: Path | None = None) -> tuple[str, int]:
    workload = f"/workspace/{trace_dir.relative_to(ROOT)}/et/{workload_basename}"
    system = f"/workspace/{(CONFIG_DIR / 'Switch.json').relative_to(ROOT)}"
    network = f"/workspace/{network_yml.relative_to(ROOT)}"
    remote_mem = "/workspace/astra-sim/examples/remote_memory/analytical/no_memory_expansion.json"
    comm = f"/workspace/{trace_dir.relative_to(ROOT)}/comm_groups.json"
    binary = "/workspace/astra-sim/build/astra_analytical/build/bin/AstraSim_Analytical_Congestion_Aware"
    cmd = [
        "docker", "run", "--rm", "--shm-size=8g",
        "-v", f"{ROOT}:/workspace", "-w", "/workspace",
        "astra-sim:latest", binary,
        f"--workload-configuration={workload}",
        f"--system-configuration={system}",
        f"--network-configuration={network}",
        f"--remote-memory-configuration={remote_mem}",
        f"--comm-group-configuration={comm}",
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    out = result.stdout + result.stderr
    if log_path:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        log_path.write_text(out)
    return out, result.returncode


def parse_astrasim_output(out: str) -> dict:
    wall = re.search(r"sys\[0\][^\n]*Wall time: (\d+)", out)
    gpu = re.search(r"sys\[0\][^\n]*GPU time: (\d+)", out)
    comm = re.search(r"sys\[0\][^\n]*Comm time: (\d+)", out)
    overlap = re.search(r"sys\[0\][^\n]*Total compute-communication overlap: (\d+)", out)
    return {
        "wall_time_cycles": int(wall.group(1)) if wall else None,
        "gpu_time_cycles": int(gpu.group(1)) if gpu else None,
        "comm_time_cycles": int(comm.group(1)) if comm else None,
        "overlap_cycles": int(overlap.group(1)) if overlap else 0,
    }


def run_local_sim(trace_dir: Path, workload_basename: str) -> int:
    """Simple topological simulator fallback (no Docker required)."""
    from chakra.schema.protobuf.et_def_pb2 import Node as ChakraNode, GlobalMetadata
    from chakra.src.third_party.utils.protolib import decodeMessage as decode_message, openFileRd

    PEAK_PERF_TFLOPS = 3
    BW_GB_S = 100
    LATENCY_NS = 500

    def get_attr(node, name, default=None):
        for a in node.attr:
            if a.name == name:
                if a.HasField("int64_val"):
                    return a.int64_val
                if a.HasField("uint64_val"):
                    return a.uint64_val
                if a.HasField("int32_val"):
                    return a.int32_val
        return default

    def duration_cycles(node) -> int:
        if node.type == 4:  # COMP_NODE
            if node.duration_micros and node.duration_micros > 0:
                return int(node.duration_micros * FREQ_GHZ * 1000)
            num_ops = get_attr(node, "num_ops", 0) or 0
            if num_ops <= 0:
                return 1
            return max(1, int(num_ops / (PEAK_PERF_TFLOPS * 1e12 / (FREQ_GHZ * 1e9))))
        if node.type in (5, 6, 7):
            size = get_attr(node, "comm_size", 0) or 0
            time_ns = (size / (BW_GB_S * 1e9)) * 1e9 + LATENCY_NS
            return max(1, int(time_ns * FREQ_GHZ / 1000))
        return 1

    n_npus = DP_SIZE * PP_SIZE * TP_SIZE
    nodes: dict[int, tuple] = {}
    base = trace_dir / "et"
    for npu in range(n_npus):
        et_path = base / f"{workload_basename}.{npu}.et"
        if not et_path.exists():
            continue
        f = openFileRd(str(et_path))
        meta = GlobalMetadata()
        decode_message(f, meta)
        node = ChakraNode()
        while decode_message(f, node):
            n = ChakraNode()
            n.CopyFrom(node)
            nodes[n.id] = (n, npu)
        f.close()

    callback_cycle: dict[int, int] = {}
    remaining = set(nodes.keys())
    while remaining:
        scheduled = []
        for nid in list(remaining):
            node, _ = nodes[nid]
            if any(d not in callback_cycle for d in node.data_deps):
                continue
            issue = max((callback_cycle.get(d, 0) for d in node.data_deps), default=0)
            callback_cycle[nid] = issue + duration_cycles(node)
            scheduled.append(nid)
        for nid in scheduled:
            remaining.discard(nid)
        if not scheduled:
            break
    return max(callback_cycle.values()) if callback_cycle else 0


# ----------------------------------------------------------------------------
# Sweep planning
# ----------------------------------------------------------------------------
def plan_runs(quick: bool = False, num_iterations: int = NUM_ITERATIONS) -> list[Cell]:
    """Build the full list of cells (ASTRA-sim runs) to execute."""
    freqs = QUICK_FREQS if quick else SWEEP_FREQS
    sizes = QUICK_SIZES_MB if quick else SWEEP_SIZES_MB
    cells: list[Cell] = []
    seen: set[tuple] = set()

    def mk(freq, size_mb, mode) -> Cell:
        return Cell(model=DEFAULT_MODEL, freq=freq, size_mb=size_mb,
                    storage=DEFAULT_STORAGE, network=DEFAULT_NETWORK,
                    mode=mode, num_iterations=num_iterations)

    def add(cell: Cell, tag: str = "main"):
        key = (cell.model, cell.freq, cell.size_mb, cell.storage, cell.network, cell.mode, cell.num_iterations)
        if key in seen:
            return
        seen.add(key)
        cell.tag = tag
        cells.append(cell)

    # Baseline (one per network -- only one network in this sweep).
    add(mk(freqs[0], sizes[0], "baseline"))
    # Dense (freq x size) grid for checkfreq_like + sync.
    for freq, size in itertools.product(freqs, sizes):
        for mode in ("checkfreq_like", "sync"):
            add(mk(freq, size, mode))
    return cells


# ----------------------------------------------------------------------------
# Execution
# ----------------------------------------------------------------------------
def execute(cells: list[Cell], skip_gen: bool, skip_sim: bool, local: bool, verbose: bool = True) -> list[dict]:
    # Pre-flight: confirm network configs exist.
    nets_needed = sorted({c.network for c in cells})
    for net in nets_needed:
        if not (CONFIG_DIR / f"{net}.yml").exists():
            raise FileNotFoundError(f"Missing network config: {net}.yml under {CONFIG_DIR}")

    # 1) Trace generation phase (cached by trace_key).
    print(f"=== Phase 1: trace generation ({len(cells)} cells, with cache) ===")
    if skip_gen:
        print("  --skip-gen: assuming traces already exist in traces/.")
    else:
        seen_keys: set[str] = set()
        for i, cell in enumerate(cells):
            key = cell.trace_key()
            if key in seen_keys:
                continue
            seen_keys.add(key)
            t0 = time.time()
            try:
                generate_trace(cell, verbose=verbose)
            except Exception as e:
                print(f"  [FAIL] {cell.trace_key()}: {e}", file=sys.stderr)
                raise
            if verbose:
                tag = "baseline" if cell.mode == "baseline" else f"{cell.mode} freq={cell.freq} size={cell.size_mb}MB"
                print(f"  [{i+1:>3}/{len(cells)}] gen {cell.model:>10} {tag:<55} {time.time()-t0:5.1f}s")

    if skip_sim:
        print("  --skip-sim: stopping after trace generation.")
        return []

    # 2) Simulation phase: one ASTRA-sim run per cell.
    print(f"\n=== Phase 2: ASTRA-sim runs ({len(cells)} cells) ===")
    rows: list[dict] = []
    for i, cell in enumerate(cells):
        model = MODELS[cell.model]
        trace_dir = TR / cell.trace_key()
        if not _trace_complete(trace_dir, model, cell.num_iterations):
            print(f"  [{i+1:>3}/{len(cells)}] MISSING trace for {cell.trace_key()}; skipping", file=sys.stderr)
            continue
        wb = workload_name(model, cell.num_iterations)
        t0 = time.time()
        if local:
            wall = run_local_sim(trace_dir, wb)
            parsed = {"wall_time_cycles": wall, "gpu_time_cycles": None, "comm_time_cycles": None, "overlap_cycles": None}
            rc = 0
        else:
            net_path = CONFIG_DIR / f"{cell.network}.yml"
            log_path = LOG_DIR / f"{cell.trace_key()}__{cell.network}.log"
            out, rc = run_astrasim(trace_dir, net_path, wb, log_path)
            parsed = parse_astrasim_output(out)
        dur = time.time() - t0
        rows.append({
            **asdict(cell),
            "trace_key": cell.trace_key(),
            "workload": wb,
            **parsed,
            "astra_returncode": rc,
            "sim_seconds": round(dur, 2),
        })
        wstr = f"wall={parsed['wall_time_cycles']:>14}" if parsed["wall_time_cycles"] else "wall=PARSE_FAIL "
        tag = "baseline" if cell.mode == "baseline" else f"{cell.mode} n={cell.freq:>3} sz={cell.size_mb:>4}MB"
        print(f"  [{i+1:>3}/{len(cells)}] {cell.model:>4} {tag:<45} {wstr}  ({dur:5.1f}s)")
    return rows


# ----------------------------------------------------------------------------
# Result post-processing
# ----------------------------------------------------------------------------
def attach_overhead(rows: list[dict]) -> list[dict]:
    """For each non-baseline row, attach overhead_pct vs matching baseline."""
    baselines: dict[tuple, dict] = {}
    for r in rows:
        if r["mode"] == "baseline":
            baselines[(r["model"], r["network"], r["num_iterations"])] = r
    for r in rows:
        if r["mode"] == "baseline":
            r["baseline_wall_time_cycles"] = r["wall_time_cycles"]
            r["overhead_pct"] = 0.0
            continue
        bl = baselines.get((r["model"], r["network"], r["num_iterations"]))
        if bl and bl["wall_time_cycles"] and r["wall_time_cycles"]:
            r["baseline_wall_time_cycles"] = bl["wall_time_cycles"]
            r["overhead_pct"] = round((r["wall_time_cycles"] - bl["wall_time_cycles"]) / bl["wall_time_cycles"] * 100, 5)
        else:
            r["baseline_wall_time_cycles"] = None
            r["overhead_pct"] = None
    return rows


def write_results(rows: list[dict]) -> None:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    cols = [
        "tag", "model", "mode", "freq", "size_mb", "storage", "network",
        "num_iterations", "wall_time_cycles", "gpu_time_cycles", "comm_time_cycles",
        "overlap_cycles", "baseline_wall_time_cycles", "overhead_pct",
        "astra_returncode", "sim_seconds", "trace_key", "workload",
    ]
    csv_path = RESULTS_DIR / "runs.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow(r)

    json_path = RESULTS_DIR / "runs.json"
    with open(json_path, "w") as f:
        json.dump({"runs": rows, "config": {
            "models": MODELS, "storage_tiers": STORAGE_TIERS, "networks": NETWORKS,
            "freqs": SWEEP_FREQS, "sizes_mb": SWEEP_SIZES_MB,
            "default": {
                "model": DEFAULT_MODEL,
                "storage": DEFAULT_STORAGE, "network": DEFAULT_NETWORK,
            },
            "num_iterations": NUM_ITERATIONS, "dp": DP_SIZE, "pp": PP_SIZE, "tp": TP_SIZE,
        }}, f, indent=2)

    # Per-cell (cf, sync) overhead pivot.
    paired: dict[tuple, dict] = {}
    for r in rows:
        if r["mode"] in ("checkfreq_like", "sync"):
            k = (r["model"], r["freq"], r["size_mb"], r["storage"], r["network"])
            paired.setdefault(k, {})[r["mode"]] = r.get("overhead_pct")
    summary_path = RESULTS_DIR / "summary.csv"
    with open(summary_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["model", "freq", "size_mb", "storage", "network",
                    "overhead_checkfreq_pct", "overhead_sync_pct",
                    "sync_minus_cf_pp", "cf_lt_sync"])
        n_ok = n_bad = 0
        for k, v in sorted(paired.items()):
            cf = v.get("checkfreq_like")
            sy = v.get("sync")
            margin = (sy - cf) if (cf is not None and sy is not None) else None
            ok = (margin is not None and margin > 0)
            n_ok += int(ok); n_bad += int(not ok and margin is not None)
            w.writerow([*k, cf, sy, margin, ok])
    print(f"\nWrote {csv_path}, {json_path}, {summary_path}")
    if paired:
        print(f"Qualitative invariant (overhead_cf < overhead_sync): "
              f"{n_ok} cells pass, {n_bad} cells fail (out of {n_ok + n_bad} pairs)")


# ----------------------------------------------------------------------------
# Entry
# ----------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="Small subset for smoke testing (~9 sims).")
    ap.add_argument("--skip-gen", action="store_true", help="Reuse cached traces under traces/.")
    ap.add_argument("--skip-sim", action="store_true", help="Generate traces but don't run ASTRA-sim.")
    ap.add_argument("--local", action="store_true", help="Use local topological sim instead of ASTRA-sim Docker.")
    ap.add_argument("--num-iterations", type=int, default=NUM_ITERATIONS,
                    help=f"Iterations per training run (default {NUM_ITERATIONS}). Same for all cells.")
    ap.add_argument("--dry-run", action="store_true", help="Print the plan and exit.")
    args = ap.parse_args()

    cells = plan_runs(quick=args.quick, num_iterations=args.num_iterations)

    print(f"Planned cells: {len(cells)}")
    counts: dict[str, int] = {}
    for c in cells:
        counts[c.tag] = counts.get(c.tag, 0) + 1
    for tag, n in sorted(counts.items()):
        print(f"  {tag or '(untagged)'}: {n}")
    if args.dry_run:
        for c in cells:
            print(f"  {c}")
        return 0

    TR.mkdir(parents=True, exist_ok=True)
    LOG_DIR.mkdir(parents=True, exist_ok=True)

    rows = execute(cells, skip_gen=args.skip_gen, skip_sim=args.skip_sim, local=args.local)
    if not rows:
        return 0
    rows = attach_overhead(rows)
    write_results(rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
