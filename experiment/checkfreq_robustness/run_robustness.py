# ----------------------------------------------------------------------------
# Model / cost helpers
# ----------------------------------------------------------------------------
def num_params_transformer(num_layers: int, hidden_size: int, vocab_size: int, sequence_len: int) -> float:
    """Same parameter-count formula as CheckWork/Model/Transformer.py."""
    n = 12 * num_layers * hidden_size * hidden_size
    n *= 1 + (13 / (12 * num_layers * hidden_size)) + (vocab_size + sequence_len) / (12 * num_layers * hidden_size)
    return n


def state_multiplier_for_target_mb(
    target_mb: float,
    model: dict,
    tp_size: int = TP_SIZE,
    pp_size: int = PP_SIZE,
) -> float:
    """Solve state_multiplier so per-rank checkpoint bytes ≈ target_mb."""
    num_params = num_params_transformer(
        model["num_layers"], model["hidden_size"],
        model["vocab_size"], model["sequence_len"],
    )
    params_per_rank = num_params / (tp_size * pp_size)
    bytes_per_rank = params_per_rank * model["bytes_per_val"] * model["scale"]
    target_bytes = target_mb * 1024 * 1024
    return target_bytes / bytes_per_rank


def storage_durations_micros(bytes_per_rank: int, storage_tier: str) -> tuple[int, int]:
    """Return (snapshot_micros, persist_micros) from a storage-tier BW pair."""
    snap_bw, pers_bw = STORAGE_TIERS[storage_tier]
    snapshot_micros = max(1, int(round(bytes_per_rank / (snap_bw * 1e9) * 1e6)))
    persist_micros = max(1, int(round(bytes_per_rank / (pers_bw * 1e9) * 1e6)))
    return snapshot_micros, persist_micros


def workload_name(model: dict, num_iterations: int) -> str:
    s = int(model["scale"] * 100)
    return (
        f"{model['name']}_{DP_SIZE}dp_{PP_SIZE}pp_{TP_SIZE}tp_{model['batch_size']}B_"
        f"{model['sequence_len']}S_{model['vocab_size']}V_{model['hidden_size']}d_"
        f"{model['bytes_per_val']}b_{s}scale_{num_iterations}iter"
    )


# ----------------------------------------------------------------------------
# Cell descriptors
# ----------------------------------------------------------------------------
@dataclass
class Cell:
    """One (model, freq, size, storage, network, mode) experimental cell."""
    model: str
    freq: int                # checkpoint_every_n
    size_mb: int             # target checkpoint MB per rank
    storage: str
    network: str
    mode: str                # "baseline" | "checkfreq_like" | "sync"
    num_iterations: int = NUM_ITERATIONS
    tag: str = ""

    def trace_key(self) -> str:
        """Cache key for the trace directory. Baseline ignores freq/size/storage."""
        if self.mode == "baseline":
            payload = (self.model, self.num_iterations, "baseline")
        else:
            payload = (self.model, self.num_iterations, self.mode, self.freq, self.size_mb, self.storage)
        h = hashlib.sha1(repr(payload).encode()).hexdigest()[:10]
        if self.mode == "baseline":
            return f"{self.model}_base_{self.num_iterations}iter_{h}"
        return f"{self.model}_{self.mode}_n{self.freq}_sz{self.size_mb}MB_{self.storage}_{self.num_iterations}iter_{h}"


